import { Types } from "mongoose";
import { Contract, type IContract } from "../models/mongo/Contract";
import { ContractTemplate } from "../models/mongo/ContractTemplate";
import { Invoice, type IInvoice } from "../models/mongo/Invoice";
import {
  isDuplicateKeyError,
  OPEN_PAYABLE_INVOICE_STATUSES,
  pickLatestStandingContract,
  standingContractQuery,
} from "../utils/standingContract";
import {
  dollarsToCents,
  invoiceTaxFromCurrentRate,
  nextInvoiceNumber,
} from "./invoice.service";

export type RenewalInvoiceContract = {
  _id: Types.ObjectId;
  customerId: number;
  customerRef?: Types.ObjectId | null;
  templateId?: Types.ObjectId | null;
  durationMonths?: number;
  renewalDueDate?: Date | null;
};

export type EnsureOpenRenewalInvoiceOptions = {
  preTaxCents?: number;
  description?: string;
  autoGenerated?: boolean;
};

export type EnsureOpenRenewalInvoiceResult = {
  invoice: IInvoice | null;
  created: boolean;
  reason?: "zero_cost";
};

export async function findStandingContracts(opts: {
  customerRef?: Types.ObjectId | string | null;
  customerId?: number | null;
  templateId?: Types.ObjectId | string | null;
  contractType?: string | null;
}): Promise<IContract[]> {
  const filter = standingContractQuery(opts);
  if (!filter) return [];
  return Contract.find(filter);
}

export function pickStandingContract(
  contracts: IContract[],
): IContract | null {
  return pickLatestStandingContract(contracts);
}

async function findOpenRenewal(contractId: Types.ObjectId): Promise<IInvoice | null> {
  return Invoice.findOne({
    contractRef: contractId,
    sourceType: "contract_renewal",
    status: { $in: [...OPEN_PAYABLE_INVOICE_STATUSES] },
  }).sort({ issuedAt: -1, createdAt: -1 });
}

async function findPaidRenewalForDue(
  contract: RenewalInvoiceContract,
): Promise<IInvoice | null> {
  if (!contract.renewalDueDate) return null;
  return Invoice.findOne({
    contractRef: contract._id,
    sourceType: "contract_renewal",
    status: "paid",
    "metadata.renewalDueDate": contract.renewalDueDate,
  }).sort({ paidAt: -1, issuedAt: -1 });
}

/**
 * Return the one open renewal invoice for this contract, or create it.
 * A duplicate-key race reloads the invoice the other writer just inserted.
 */
export async function ensureOpenRenewalInvoice(
  contract: RenewalInvoiceContract,
  options?: EnsureOpenRenewalInvoiceOptions,
): Promise<EnsureOpenRenewalInvoiceResult> {
  const existingOpen = await findOpenRenewal(contract._id);
  if (existingOpen) return { invoice: existingOpen, created: false };

  const paidForDue = await findPaidRenewalForDue(contract);
  if (paidForDue) return { invoice: paidForDue, created: false };

  let preTaxCents = options?.preTaxCents ?? 0;
  let templateLabel: string | undefined;
  if (contract.templateId) {
    const template = await ContractTemplate.findById(contract.templateId)
      .select("cost label")
      .lean();
    templateLabel = template?.label;
    if (options?.preTaxCents == null) {
      preTaxCents = dollarsToCents(template?.cost ?? 0);
    }
  }
  if (preTaxCents <= 0) return { invoice: null, created: false, reason: "zero_cost" };

  const tax = await invoiceTaxFromCurrentRate(preTaxCents);
  const issuedAt = new Date();
  const description =
    options?.description ||
    `Contract renewal${templateLabel ? `: ${templateLabel}` : ""}`;

  try {
    const invoice = await Invoice.create({
      number: await nextInvoiceNumber(issuedAt),
      customerId: contract.customerId,
      customerRef: contract.customerRef ?? undefined,
      sourceType: "contract_renewal",
      contractRef: contract._id,
      templateRef: contract.templateId ?? null,
      lineItems: [{ description, amountCents: preTaxCents }],
      amountCents: preTaxCents + tax.taxCents,
      currency: "USD",
      status: "open",
      dueDate: contract.renewalDueDate ?? null,
      issuedAt,
      metadata: {
        durationMonths: contract.durationMonths || 12,
        renewalDueDate: contract.renewalDueDate ?? null,
        autoGenerated: options?.autoGenerated ?? true,
        templateLabel,
      },
      taxRatePercent: tax.taxRatePercent,
      taxCents: tax.taxCents,
      taxOverridden: tax.taxOverridden,
    });
    return { invoice, created: true };
  } catch (err) {
    if (!isDuplicateKeyError(err)) throw err;
    const raced = await findOpenRenewal(contract._id);
    if (raced) return { invoice: raced, created: false };
    throw err;
  }
}
