import { env } from "../config/env";
import { Contract } from "../models/mongo/Contract";
import {
  excludeDeletedCustomerRefs,
  loadDeletedCustomerIds,
} from "../models/mongo/Customer";
import { ensureOpenRenewalInvoice } from "../services/renewalInvoice";
import { endOfDay, startOfDay } from "../utils/contractDates";

/**
 * Create open renewal invoices for contracts due within the lead window.
 * Idempotent: skips contracts that already have an open/draft/paid renewal
 * invoice for the current renewalDueDate period.
 */
export async function runRenewalInvoiceJob(): Promise<{
  created: number;
  skipped: number;
  errors: number;
}> {
  const leadDays = env.renewalInvoiceLeadDays;
  const today = startOfDay(new Date());
  const windowEnd = endOfDay(
    new Date(today.getTime() + leadDays * 24 * 60 * 60 * 1000),
  );

  const hideDeleted = excludeDeletedCustomerRefs(await loadDeletedCustomerIds());
  const contracts = await Contract.find({
    renewalDueDate: { $ne: null, $lte: windowEnd },
    temporary: { $ne: true },
    customerRef: {
      $ne: null,
      ...(hideDeleted.customerRef as Record<string, unknown> | undefined),
    },
  }).limit(500);

  let created = 0;
  let skipped = 0;
  let errors = 0;

  for (const contract of contracts) {
    try {
      if (!contract.renewalDueDate) {
        skipped += 1;
        continue;
      }

      const result = await ensureOpenRenewalInvoice(contract, {
        autoGenerated: true,
      });
      if (result.created) {
        created += 1;
        continue;
      }
      skipped += 1;
    } catch (err) {
      errors += 1;
      console.error(
        `[renewal-invoices] failed for contract ${contract._id}`,
        err,
      );
    }
  }

  return { created, skipped, errors };
}
