import { Router } from "express";
import { authenticate, requirePermission } from "../middleware/auth.middleware";
import {
  uploadInboxMedia,
  uploadInboxMediaMiddleware,
} from "../controllers/inboxMedia.controller";
import {
  addInboxNote,
  callInboxConversation,
  cancelInboxScheduled,
  closeInboxConversation,
  getInboxContext,
  getInboxTimeline,
  linkInboxCustomer,
  listInboxChannels,
  listInboxConversations,
  listInboxScheduled,
  listInboxTemplates,
  blockInboxConversation,
  deleteInboxConversation,
  markInboxRead,
  markInboxUnread,
  pinInboxConversation,
  reopenInboxConversation,
  scheduleInboxSms,
  unblockInboxConversation,
  unpinInboxConversation,
  searchInboxCustomers,
  sendInboxEmail,
  sendInboxSms,
  uploadInboxEmailAttachmentsMiddleware,
  getInboxEmailFormat,
  setInboxEmailFormat,
  rateCallTranscript,
  dismissCallTaskPrompt,
  confirmInboxOptOut,
  dismissInboxOptOut,
} from "../controllers/inboxes.controller";

const router = Router();

router.use(authenticate);

router.post(
  "/media",
  requirePermission("messages:write"),
  uploadInboxMediaMiddleware,
  uploadInboxMedia,
);
router.post(
  "/scheduled/:scheduledId/cancel",
  requirePermission("messages:write"),
  cancelInboxScheduled,
);
router.get("/channels", requirePermission("messages:read"), listInboxChannels);
router.get("/templates", requirePermission("messages:read"), listInboxTemplates);
router.get("/customers", requirePermission("messages:read"), searchInboxCustomers);
router.get("/conversations", requirePermission("messages:read"), listInboxConversations);
router.get(
  "/conversations/:id/timeline",
  requirePermission("messages:read"),
  getInboxTimeline,
);
router.get(
  "/conversations/:id/context",
  requirePermission("messages:read"),
  getInboxContext,
);
router.post(
  "/conversations/:id/read",
  requirePermission("messages:read"),
  markInboxRead,
);
router.post(
  "/conversations/:id/close",
  requirePermission("messages:write"),
  closeInboxConversation,
);
router.post(
  "/conversations/:id/reopen",
  requirePermission("messages:write"),
  reopenInboxConversation,
);
router.post(
  "/conversations/:id/unread",
  requirePermission("messages:write"),
  markInboxUnread,
);
router.post(
  "/conversations/:id/pin",
  requirePermission("messages:write"),
  pinInboxConversation,
);
router.post(
  "/conversations/:id/unpin",
  requirePermission("messages:write"),
  unpinInboxConversation,
);
router.post(
  "/conversations/:id/block",
  requirePermission("messages:write"),
  blockInboxConversation,
);
router.post(
  "/conversations/:id/unblock",
  requirePermission("messages:write"),
  unblockInboxConversation,
);
router.delete(
  "/conversations/:id",
  requirePermission("messages:write"),
  deleteInboxConversation,
);
router.get(
  "/conversations/:id/scheduled",
  requirePermission("messages:read"),
  listInboxScheduled,
);
router.post(
  "/conversations/:id/sms",
  requirePermission("messages:write"),
  sendInboxSms,
);
router.post(
  "/conversations/:id/sms/schedule",
  requirePermission("messages:write"),
  scheduleInboxSms,
);
router.post(
  "/conversations/:id/email",
  requirePermission("messages:write"),
  uploadInboxEmailAttachmentsMiddleware,
  sendInboxEmail,
);
router.get(
  "/email-format",
  requirePermission("messages:read"),
  getInboxEmailFormat,
);
router.put(
  "/email-format",
  requirePermission("messages:write"),
  setInboxEmailFormat,
);
router.post(
  "/conversations/:id/call",
  requirePermission("messages:write"),
  callInboxConversation,
);
router.post(
  "/conversations/:id/link-customer",
  requirePermission("messages:write"),
  linkInboxCustomer,
);
router.post(
  "/conversations/:id/context",
  requirePermission("messages:write"),
  addInboxNote,
);
router.put(
  "/messages/:communicationId/transcript-rating",
  requirePermission("messages:write"),
  rateCallTranscript,
);
router.post(
  "/messages/:communicationId/task-prompt/dismiss",
  requirePermission("messages:write"),
  dismissCallTaskPrompt,
);
router.post(
  "/messages/:id/opt-out/confirm",
  requirePermission("messages:write"),
  confirmInboxOptOut,
);
router.post(
  "/messages/:id/opt-out/dismiss",
  requirePermission("messages:write"),
  dismissInboxOptOut,
);

export default router;
